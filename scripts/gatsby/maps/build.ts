/*
 * GATSBY.EXE: builds public/games/gatsby/maps.js from the stage map sources.
 *
 *   node scripts/gatsby/maps/build.ts           write maps.js
 *   node scripts/gatsby/maps/build.ts --check   exit 1 if maps.js is out of date
 *
 * Each file in stages/ draws one stage onto a Grid of characters with
 * put/rect/fill/row (tile coordinates; 16px tiles; '.' is empty). A character
 * means nothing here: stages.js gives each stage a tileset and a legend, and
 * the legend says what a character is, either a terrain name from the tileset
 * (ground, ladders, water, spikes...) or { e: 'type', ...props } for something
 * that moves. P (start), K (checkpoint), G (goal), * (item) and + (orange)
 * are shared by every stage (GG.ENTITY_LEGEND in core.js).
 *
 * To change a map: edit its stage file, run this script, then run the solver
 * to make sure the stage can still be finished. A stage file can also return
 * `info`, which lands in GG.MAPINFO (arena columns, room backdrops, the green
 * light's stops); keep it next to the drawing it describes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { GAME_DIR } from '../lib/game.ts';
import type { StageMap } from './grid.ts';
import { stage1 } from './stages/s1.ts';
import { stage2_1 } from './stages/s2-1.ts';
import { stage2_2 } from './stages/s2-2.ts';
import { stage3 } from './stages/s3.ts';
import { stage4_1 } from './stages/s4-1.ts';
import { stage4_2 } from './stages/s4-2.ts';
import { stage5 } from './stages/s5.ts';
import { stage6 } from './stages/s6.ts';
import { stage7 } from './stages/s7.ts';
import { stage8 } from './stages/s8.ts';
import { stage9 } from './stages/s9.ts';

const OUT = path.join(GAME_DIR, 'maps.js');
const STAGES = [stage1, stage2_1, stage2_2, stage3, stage4_1, stage4_2, stage5, stage6, stage7, stage8, stage9];

/* JSON with ', ' and ': ' between items, so the output reads like the rest of the file. */
function json(v: unknown): string {
  if (Array.isArray(v)) return '[' + v.map(json).join(', ') + ']';
  if (v && typeof v === 'object') {
    return '{' + Object.entries(v).map(([k, x]) => JSON.stringify(k) + ': ' + json(x)).join(', ') + '}';
  }
  return JSON.stringify(v);
}

/* A map row as a JS string: single quotes unless the row itself has one. */
const rowLiteral = (r: string) => (r.includes("'") ? JSON.stringify(r) : JSON.stringify(r).replace(/"/g, "'"));

export function render(maps: StageMap[]): string {
  let s = "'use strict';\n/* GATSBY.EXE: stage maps (generated by scripts/gatsby/maps/build.ts; run `node scripts/gatsby/maps/build.ts`). */\n(() => {\n  GG.MAPS = {\n";
  for (const m of maps) {
    s += `    '${m.key}': [\n`;
    for (const r of m.rows) s += `      ${rowLiteral(r)},\n`;
    s += '    ],\n';
  }
  s += '  };\n';
  // Keys are written in stage order (a plain object would put '1', '3'... first).
  const info = maps.filter((m) => m.info).map((m) => JSON.stringify(m.key) + ': ' + json(m.info));
  s += '  GG.MAPINFO = {' + info.join(', ') + '};\n})();\n';
  return s;
}

/* The body of a maps.js, without its header comment, split per stage. */
function stageChunks(src: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const m of src.matchAll(/^ {4}'([^']+)': \[\n([\s\S]*?)^ {4}\],\n/gm)) out.set(m[1], m[2]);
  const info = src.match(/^ {2}GG\.MAPINFO = .*$/m);
  out.set('MAPINFO', info ? info[0] : '');
  return out;
}

const maps = STAGES.map((f) => f());
const text = render(maps);

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const body = (s: string) => s.split('\n').slice(2).join('\n');
  if (body(cur) === body(text)) {
    console.log('maps.js is up to date');
    process.exit(0);
  }
  const a = stageChunks(cur), b = stageChunks(text);
  const keys = new Set([...a.keys(), ...b.keys()]);
  const stale = [...keys].filter((k) => a.get(k) !== b.get(k));
  console.error(`maps.js is out of date (differs in: ${stale.join(', ') || 'layout'}); run node scripts/gatsby/maps/build.ts`);
  process.exit(1);
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote', path.relative(process.cwd(), OUT), maps.map((m) => m.key).join(' '));
}
